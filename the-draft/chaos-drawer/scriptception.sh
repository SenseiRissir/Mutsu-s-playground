# Function to generate random content lines
generate_content() {
    local num_lines=$1
    for ((i=0; i<num_lines; i++)); do
        local subject="${SUBJECTS[$RANDOM % ${#SUBJECTS[@]}]}"
        local action="${ACTIONS[$RANDOM % ${#ACTIONS[@]}]}"
        local adj="${ADJECTIVES[$RANDOM % ${#ADJECTIVES[@]}]}"
        local subj2="${SUBJECTS[$RANDOM % ${#SUBJECTS[@]}]}"

        echo "    \"${subject} ${action} ${subj2}. It's ${adj}.\""
    done
}

