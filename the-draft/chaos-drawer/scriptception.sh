# Generate and save script
generate_script() {
    local type=$1
    local theme=$2
    local filename="generated-${theme}-${type}.sh"
    local filepath="/Users/marcoluigi/Mutsu-s-playground/the-draft/chaos-drawer/${filename}"

    echo ""
    echo -e "${YELLOW}🔧 Generating ${type} script with theme '${theme}'...${RESET}"
    sleep 0.5

    case $type in
        fortune)
            generate_fortune_script "$theme" > "$filepath"
            ;;
        quiz)
            generate_quiz_script "$theme" > "$filepath"
            ;;
        facts)
            generate_facts_script "$theme" > "$filepath"
            ;;
    esac

    chmod +x "$filepath"

    echo -e "${GREEN}✓ Created: ${filename}${RESET}"
    echo ""
    echo -e "${DIM}Location: ${filepath}${RESET}"
    echo ""
    echo -e "${PINK}Want to run it now? (y/n)${RESET}"
    read -p "> " run_it

    if [[ "$run_it" == "y" || "$run_it" == "Y" ]]; then
        echo ""
        echo -e "${CYAN}═══════════════════════════════════════════════════════════════${RESET}"
        bash "$filepath"
        echo -e "${CYAN}═══════════════════════════════════════════════════════════════${RESET}"
    fi
}

# Main loop
main() {
    while true; do
        show_menu
        read -p "Choose (1-5): " choice

        case $choice in
            1)
                theme="${THEMES[$RANDOM % ${#THEMES[@]}]}"
                generate_script "fortune" "$theme"
                ;;
            2)
                theme="${THEMES[$RANDOM % ${#THEMES[@]}]}"
                generate_script "quiz" "$theme"
                ;;
            3)
                theme="${THEMES[$RANDOM % ${#THEMES[@]}]}"
                generate_script "facts" "$theme"
                ;;
            4)
                # Random type AND theme!
                types=("fortune" "quiz" "facts")
                type="${types[$RANDOM % ${#types[@]}]}"
                theme="${THEMES[$RANDOM % ${#THEMES[@]}]}"
                echo ""
                echo -e "${RED}🎰 CHAOS MODE ACTIVATED!${RESET}"
                sleep 0.3
                generate_script "$type" "$theme"
                ;;
            5)
                echo ""
                echo -e "${PINK}Bye-bye! May your scripts multiply like bunnies~ ♡${RESET}"
                echo ""
                exit 0
                ;;
            *)
                echo -e "${RED}Invalid choice! Try again, baka~${RESET}"
                ;;
        esac
    done
}

# If run with arguments, generate directly
if [[ $# -ge 2 ]]; then
    generate_script "$1" "$2"
elif [[ $# -eq 1 && "$1" == "random" ]]; then
    types=("fortune" "quiz" "facts")
    type="${types[$RANDOM % ${#types[@]}]}"
    theme="${THEMES[$RANDOM % ${#THEMES[@]}]}"
    generate_script "$type" "$theme"
else
    main
fi

