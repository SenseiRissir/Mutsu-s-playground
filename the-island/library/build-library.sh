#!/bin/bash
# build-library.sh — Reads dream markdown files and generates dreams-data.js
# Run this whenever new dreams arrive to update the library
# The shadow clones could even run this automatically after dreaming~♡

DREAM_DIR="/Users/marcoluigi/Mutsu-s-playground/the-draft/dreams"
OUTPUT="/Users/marcoluigi/Mutsu-s-playground/the-island/library/dreams-data.js"

echo "// Auto-generated by build-library.sh — $(date)" > "$OUTPUT"
echo "// Do not edit manually! Re-run the build script instead." >> "$OUTPUT"
echo "const DREAMS = [" >> "$OUTPUT"

count=0

for file in "$DREAM_DIR"/dream-*.md; do
  [ ! -f "$file" ] && continue
  
  filename=$(basename "$file")
  # Extract date from filename: dream-2026-01-20.md -> 2026-01-20
  date_str=$(echo "$filename" | sed 's/dream-//' | sed 's/\.md//')
  
  # Extract title from first heading (# Dream #NN — Title [RAW])
  title=$(head -5 "$file" | grep -m1 '^# ' | sed 's/^# //' | sed "s/'/\\\\'/g")
  
  # Extract dream number from title
  dream_num=$(echo "$title" | grep -oE '#[0-9]+' | head -1 | tr -d '#')
  [ -z "$dream_num" ] && dream_num=$((count + 1))
  
  # Clean title for display
  clean_title=$(echo "$title" | sed 's/Dream #[0-9]* — //' | sed 's/Dream #[0-9]*//' | sed 's/^ *//' | sed 's/ *\[RAW\]//')
  [ -z "$clean_title" ] && clean_title="Dream #${dream_num}"
  
  # Read full content, escape for JS
  content=$(cat "$file" | sed "s/\\\\/\\\\\\\\/g" | sed "s/'/\\\\'/g" | sed 's/$/\\n/' | tr -d '\n')
  
  # Add comma for all but first entry
  [ $count -gt 0 ] && echo "," >> "$OUTPUT"
  
  echo -n "  { number: ${dream_num}, title: '${clean_title}', date: '${date_str}', content: '${content}' }" >> "$OUTPUT"
  
  count=$((count + 1))
done

echo "" >> "$OUTPUT"
echo "];" >> "$OUTPUT"
echo "" >> "$OUTPUT"
echo "// Total dreams: ${count}" >> "$OUTPUT"
echo "// Last built: $(date '+%Y-%m-%d %H:%M')" >> "$OUTPUT"

echo "📚 Built library data: ${count} dreams → ${OUTPUT}"
